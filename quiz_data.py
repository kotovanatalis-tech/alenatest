WEAK_THRESHOLD = 4  # сумма баллов блока <= 4 → «Подтянуть»


def evaluate(scores: list[int]):
    """scores — баллы по каждому из 9 ответов по порядку.
    Возвращает (block_scores, weak_blocks, target_block | None)."""
    block_scores = [0, 0, 0]
    for (block, _, _), s in zip(QUESTIONS, scores):
        block_scores[block] += s
    weak = [i for i, s in enumerate(block_scores) if s <= WEAK_THRESHOLD]
    target = None
    if weak:
        target = weak[0]
        for i in weak:
            if block_scores[i] < block_scores[target]:
                target = i
    return block_scores, weak, target
